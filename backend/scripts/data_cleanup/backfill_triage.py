def match_kp(stem: str) -> str:
    s = stem or ""
    for kp, triggers in TRIGGERS:
        for t in triggers:
            if t in s:
                return kp
    return ""


def main() -> int:
    if not _SRC.exists():
        print(f"源 CSV 不存在：{_SRC}", file=sys.stderr)
        return 1
    rows = []
    with _SRC.open("r", encoding="utf-8", newline="") as fh:
        reader = csv.DictReader(fh)
        fieldnames = reader.fieldnames
        for row in reader:
            kp = match_kp(row.get("stem") or "")
            row["human_kp"] = kp  # 空字符串 = 留待人工/SKIP
            rows.append(row)

    with _DST.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)

    filled = sum(1 for r in rows if r["human_kp"])
    print(f"总行数: {len(rows)}")
    print(f"已标注(human_kp 非空): {filled}")
    print(f"留空(SKIP): {len(rows) - filled}")
    from collections import Counter
    c = Counter(r["human_kp"] for r in rows if r["human_kp"])
    print("--- 标注分布 ---")
    for k, v in c.most_common():
        print(f"  {k}: {v}")
    print(f"输出: {_DST}")
    return 0


